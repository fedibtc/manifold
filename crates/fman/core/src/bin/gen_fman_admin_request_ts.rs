//! Generates the committed TypeScript `AdminRequest` union at
//! `operator-ui/packages/types/src/generated/adminRequest.ts`.
//!
//! The union used to be written by hand beside the Rust enum, which is a copy
//! of the contract rather than the contract. `ts-rs` derives it from
//! `AdminRequest` itself, so a verb added, renamed or reshaped in Rust changes
//! this file or fails the paired freshness test
//! (`tests/admin_request_ts.rs`) — the same arrangement the contract fixtures
//! already use, and for the same reason.
//!
//! Run via `just gen-contract-fixtures`, which regenerates every generated
//! artifact together.
//!
//! `ts-rs` would normally emit one file per type from a magic `export_bindings`
//! test, then need a shell script to concatenate and de-`import` them. One type
//! needs none of that: `export_to_string` hands over the declaration and this
//! binary owns the header and the path.

use std::path::PathBuf;

use fman_core::admin::AdminRequest;
use ts_rs::{Config, TS};

/// Written once above the generated declaration.
///
/// `SeatId` and `FederationId` reach the union through `#[ts(type = "...")]`
/// overrides on the fields. Both are aliases of `string` declared in
/// TypeScript, so there is nothing for `ts-rs` to derive — and letting them
/// widen to `string` would throw away naming the dashboard reads by.
///
/// The file is excluded from Biome (`biome.json`, `files.includes`): it is
/// generated, never hand-edited, and formatting it would only make the
/// byte-for-byte freshness assertion fail.
const HEADER: &str = "\
// Generated by crates/fman/core/src/bin/gen_fman_admin_request_ts.rs from
// AdminRequest in crates/fman/core/src/admin.rs. Do not edit by hand: run
// `just gen-contract-fixtures`. Freshness is asserted by
// crates/fman/core/tests/admin_request_ts.rs, so an edit here fails Rust CI.

import type { SeatId } from '../fleet';
import type { FederationId } from '../funds';
";

pub fn output_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../operator-ui/packages/types/src/generated/adminRequest.ts")
}

/// The whole file, header included. Shared with the freshness test so both
/// sides compare the same bytes.
///
/// `ts-rs` leaves a trailing space on the line before each carried doc comment,
/// which the repository's pre-commit hook refuses. Stripping it here is what
/// makes the output committable at all — and it has to happen in this one
/// function, not in the generator alone, or the freshness test would compare
/// the committed file against unstripped output and always fail.
pub fn generated() -> String {
    // The default config, not the environment's: `TS_RS_EXPORT_DIR` and friends
    // must not be able to change a committed file from the caller's shell.
    let declaration =
        AdminRequest::export_to_string(&Config::default()).expect("AdminRequest exports");
    let body: String = declaration
        .lines()
        .map(|line| format!("{}\n", line.trim_end()))
        .collect();
    format!("{HEADER}\n{}\n", body.trim_end())
}

fn main() {
    let path = output_path();
    std::fs::create_dir_all(path.parent().expect("output path has a directory"))
        .expect("create the generated directory");
    std::fs::write(&path, generated()).unwrap_or_else(|err| panic!("write {path:?}: {err}"));
    println!("wrote {}", path.display());
}
